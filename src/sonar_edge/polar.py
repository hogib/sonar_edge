"""Back-projection of the dataset's fan images to polar sonar frames (M8 front end).

The dataset has no raw ARIS data: every frame is already a 320x480 Cartesian
fan image. To exercise the C front end's polar mode (runtime/frontend.c), the
fan images are sampled back onto a polar grid, n_samples range bins (near to
far) x n_beams beams (beam 0 leftmost), bilinearly at bin and beam centres,
with the measured fan geometry (FAN, same values as se_fan_watertank in
frontend.c). These frames are synthetic: they carry the fan image's
interpolation and have no ARIS beam pattern, so results on them test the
remap, not performance on real raw data.

  uv run python -m sonar_edge.polar export OUT_DIR [--beams 128] [--samples 439]
      writes OUT_DIR/polar.u8 (all frames, n_samples x n_beams each) and OUT_DIR/polar.json
  uv run python -m sonar_edge.polar golden
      prints runtime/tests/frontend_golden.h (fan-mode checks against the Python pipeline)
"""

import argparse
import json
from pathlib import Path

import numpy as np
from PIL import Image

from .data import FRAME_H, FRAME_W, load_frames

# measured from the dataset; see the comment on se_fan_watertank in runtime/frontend.c
FAN = dict(width=FRAME_W, height=FRAME_H, apex_u=160.0, apex_v=602.7, fov_deg=30.0, r_min_px=138.6, r_max_px=578.0)
N_BEAMS = 128                                                # ARIS Explorer 3000
N_SAMPLES = int(round(FAN["r_max_px"] - FAN["r_min_px"]))    # one range bin per fan pixel: 439


def bilinear(img, u, v):
    """Sample img (HxW) at continuous coordinates (pixel centres at +0.5); outside -> 0."""
    x, y = u - 0.5, v - 0.5
    x0, y0 = np.floor(x).astype(int), np.floor(y).astype(int)
    fx, fy = x - x0, y - y0
    h, w = img.shape
    pad = np.zeros((h + 2, w + 2), np.float64)  # one ring of zeros: samples off the image read 0
    pad[1:-1, 1:-1] = img
    xi, yi = np.clip(x0 + 1, 0, w), np.clip(y0 + 1, 0, h)
    a, b = pad[yi, xi], pad[yi, xi + 1]
    c, d = pad[yi + 1, xi], pad[yi + 1, xi + 1]
    return (a * (1 - fx) + b * fx) * (1 - fy) + (c * (1 - fx) + d * fx) * fy


def polar_grid(n_beams=N_BEAMS, n_samples=N_SAMPLES, g=FAN):
    """Fan-image coordinates (u, v) of every (range bin, beam) centre, each n_samples x n_beams."""
    r = g["r_min_px"] + (np.arange(n_samples) + 0.5) * (g["r_max_px"] - g["r_min_px"]) / n_samples
    th = np.radians(-g["fov_deg"] / 2 + (np.arange(n_beams) + 0.5) * g["fov_deg"] / n_beams)
    u = g["apex_u"] + r[:, None] * np.sin(th)[None, :]
    v = g["apex_v"] - r[:, None] * np.cos(th)[None, :]
    return u, v


def to_polar(img, n_beams=N_BEAMS, n_samples=N_SAMPLES):
    u, v = polar_grid(n_beams, n_samples)
    return np.clip(np.round(bilinear(img.astype(np.float64), u, v)), 0, 255).astype(np.uint8)


def cmd_export(args):
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    frames = load_frames()
    with open(out / "polar.u8", "wb") as fh:
        for f in frames:
            fh.write(to_polar(f.load(), args.beams, args.samples).tobytes())
    (out / "polar.json").write_text(json.dumps({"beams": args.beams, "samples": args.samples, "fan": FAN,
                                                "index": [f.index for f in frames]}))
    print(f"wrote {len(frames)} polar frames ({args.samples} x {args.beams}) to {out}")


def fnv1a(b: bytes) -> int:
    h = 0x811C9DC5
    for x in b:
        h = ((h ^ x) * 0x01000193) & 0xFFFFFFFF
    return h


def lcg_frame(seed, w=FRAME_W, h=FRAME_H):
    """Same generator as tests/test_frontend.c: x = x * 1664525 + 1013904223, byte = x >> 24."""
    out = np.empty(w * h, np.uint8)
    x = seed
    for i in range(w * h):
        x = (x * 1664525 + 1013904223) & 0xFFFFFFFF
        out[i] = x >> 24
    return out.reshape(h, w)


def net_input(img, w, h):
    """The network input the training/eval pipeline makes from a fan image (dataset._prep + c_eval.export_pgm)."""
    from .dataset import FrameDataset
    ds = FrameDataset.__new__(FrameDataset)
    s = img.shape[1] / w
    ds.scale = int(s) if s == int(s) else s
    ds.h, ds.w = h, w
    return np.round(ds._prep(img) * 255).astype(np.uint8)


def cmd_golden(args):
    """Fan-mode expectations: FNV-1a hashes of the pipeline's network input for synthetic frames."""
    sizes = [(240, 360), (160, 240), (320, 480), (200, 300)]  # (w, h): small@360, small@240, wide, odd factor
    lines = ["/* Generated by `python -m sonar_edge.polar golden`: FNV-1a hash of the network input",
             " * the Python pipeline makes from 320x480 test frames (sonar_edge.polar.net_input:",
             " * Pillow BOX resize, or block mean for integer factors). Frame kind 0: LCG noise",
             " * (seed 12345); 1: horizontal ramp x mod 256; 2: all 255; 3: vertical stripes 0/255;",
             " * 4: LCG noise (seed 777) quantised to multiples of 2 (exercises ties in the mean). */",
             "static const struct { int kind, w, h; uint32_t hash; } fe_golden[] = {"]
    frames = [lcg_frame(12345),
              np.tile((np.arange(FRAME_W) % 256).astype(np.uint8), (FRAME_H, 1)),
              np.full((FRAME_H, FRAME_W), 255, np.uint8),
              np.tile(np.where(np.arange(FRAME_W) % 2 == 0, 0, 255).astype(np.uint8), (FRAME_H, 1)),
              lcg_frame(777) & 0xFE]
    for kind, img in enumerate(frames):
        for w, h in sizes:
            lines.append(f"    {{{kind}, {w}, {h}, 0x{fnv1a(net_input(img, w, h).tobytes()):08x}u}},")
    lines.append("};")
    print("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(required=True)
    e = sub.add_parser("export")
    e.add_argument("out")
    e.add_argument("--beams", type=int, default=N_BEAMS)
    e.add_argument("--samples", type=int, default=N_SAMPLES)
    e.set_defaults(func=cmd_export)
    g = sub.add_parser("golden")
    g.set_defaults(func=cmd_golden)
    args = ap.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
